# Get configuration value by key
get_config() {
    local key="$1"
    local default_value="${2:-}"
    
    case "$key" in
        api_key|api-key)
            echo "${CONFLUENT_CLOUD_API_KEY:-$default_value}"
            ;;
        api_secret|api-secret)
            echo "${CONFLUENT_CLOUD_API_SECRET:-$default_value}"
            ;;
        environment|env)
            echo "${CONFLUENT_ENVIRONMENT_ID:-$default_value}"
            ;;
        cluster)
            echo "${CONFLUENT_CLUSTER_ID:-$default_value}"
            ;;
        bootstrap_servers|bootstrap-servers)
            echo "${CONFLUENT_BOOTSTRAP_SERVERS:-$default_value}"
            ;;
        schema_registry_url|schema-registry-url)
            echo "${CONFLUENT_SCHEMA_REGISTRY_URL:-$default_value}"
            ;;
        region)
            echo "${CONFLUENT_REGION:-$default_value}"
            ;;
        cloud)
            echo "${CONFLUENT_CLOUD:-$default_value}"
            ;;
        *)
            echo "$default_value"
            ;;
    esac
}

# Validate TableFlow environment variables
validate_tableflow_env() {
    local required_vars=(
        "CC_TF_API_KEY"
        "CC_TF_API_SECRET"
        "CC_ORG_ID"
        "CC_ENV"
        "CONFLUENT_REGION"
    )
    
    local missing_vars=()
    
    for var in "${required_vars[@]}"; do
        if [[ -z "${!var}" ]]; then
            missing_vars+=("$var")
        fi
    done
    
    if [[ ${#missing_vars[@]} -gt 0 ]]; then
        error "Missing required TableFlow environment variables:"
        for var in "${missing_vars[@]}"; do
            echo -e "  ${RED}${ERROR}${RESET} $var"
        done
        info "Please configure these variables in your .env file"
        return 1
    fi
    
    success "All required TableFlow environment variables are set"
    return 0
}

# Generate TableFlow catalog URL
generate_tableflow_catalog_url() {
    local region="${CONFLUENT_REGION:-us-west-2}"
    local org_id="${CC_ORG_ID}"
    local env_id="${CC_ENV}"
    
    if [[ -z "$org_id" || -z "$env_id" ]]; then
        error "Organization ID and Environment ID are required to generate TableFlow catalog URL"
        return 1
    fi
    
    echo "https://tableflow.${region}.aws.confluent.cloud/iceberg/catalog/organizations/${org_id}/environments/${env_id}"
}

# Generate TableFlow properties file
generate_tableflow_properties() {
    local output_file="$1"
    local connector_name="${2:-iceberg}"
    
    if [[ -z "$output_file" ]]; then
        error "Output file not specified for TableFlow properties generation"
        return 1
    fi
    
    # Validate required environment variables
    validate_tableflow_env || return 1
    
    # Generate catalog URL if not provided
    local catalog_url="${CC_TF_CATALOG_URL}"
    if [[ -z "$catalog_url" ]]; then
        catalog_url=$(generate_tableflow_catalog_url)
        if [[ $? -ne 0 ]]; then
            return 1
        fi
    fi
    
    progress "Generating TableFlow properties file: $output_file"
    
    cat > "$output_file" << EOF
# Generated by cc-tableflow-properties on $(date)
# TableFlow Iceberg Connector Configuration

# Connector Configuration
connector.name=${connector_name}

# Iceberg Catalog Configuration
iceberg.catalog.type=rest
iceberg.rest-catalog.oauth2.credential=${CC_TF_API_KEY}:${CC_TF_API_SECRET}
iceberg.rest-catalog.security=OAUTH2
iceberg.rest-catalog.uri=${catalog_url}
iceberg.rest-catalog.vended-credentials-enabled=true

# File System Configuration
fs.native-s3.enabled=true
s3.region=${CONFLUENT_REGION:-us-west-2}

# Security Configuration
iceberg.security=read_only
EOF
    
    success "Generated TableFlow properties: $output_file"
    return 0
}

# Initialize configuration
init_config() {
    load_env || return 1
    validate_env || return 1
    validate_optional_env
    return 0
}

# Initialize TableFlow configuration
init_tableflow_config() {
    load_env || return 1
    validate_tableflow_env || return 1
    return 0
}
